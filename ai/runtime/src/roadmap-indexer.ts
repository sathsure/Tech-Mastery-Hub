/**
 * Indexes the generated roadmaps (roadmap/topics, roadmap/roles) as one "roadmap" entry per file,
 * so "Roadmap to become a DevOps engineer" or "Where do I start?" return the whole checklist.
 */
import { posix } from "node:path";
import type { QuestionEntry } from "./question-index-contracts.js";
import { cleanHeading, extractKeywords, hash, summarize, type Lookups } from "./question-indexer.js";

const MARKER = "<!-- generated by ai/runtime/src/roadmap-generator.ts";

export function isGeneratedRoadmap(path: string, content: string): boolean {
  return /^roadmap\/(topics|roles)\//.test(path) && content.includes(MARKER);
}

/** "database-sql" → "database/sql" when that is a known topic. */
function topicFromSlug(slug: string, lookups: Lookups): string | null {
  const topics = [...new Set([...lookups.concepts, ...Object.keys(lookups.topicAliases)])];
  return topics.find(topic => topic.replace(/[^a-z0-9]+/gi, "-").toLowerCase() === slug) ?? null;
}

/** Phrases a user might type to find this roadmap. */
function roadmapNames(path: string, subject: string, isIndex: boolean, isRole: boolean): string[] {
  if (isIndex && path.startsWith("roadmap/topics/")) return ["where to start", "start here", "learning tracks", "learning track"];
  if (isIndex) return ["role roadmaps", "career roadmaps"];
  if (isRole) return [`${subject} roadmap`];
  return [`${subject} study path`, `${subject} roadmap`, `${subject} learning path`, `learn ${subject}`];
}

export function buildRoadmapEntry(path: string, content: string, lookups: Lookups): QuestionEntry {
  const lines = content.split("\n");
  const titleAt = lines.findIndex(line => /^# /.test(line));
  const title = cleanHeading(lines[titleAt]?.slice(2) ?? posix.basename(path, ".md"));
  const answer = lines.slice(titleAt + 1).join("\n").trim();
  const isIndex = posix.basename(path) === "README.md";
  const isRole = path.startsWith("roadmap/roles/") && !isIndex;
  const topic = !isIndex && !isRole ? topicFromSlug(posix.basename(path, ".md"), lookups) : null;
  // Topics this roadmap links to (its study paths), for search narrowing and follow-up suggestions.
  const linked = [...new Set([...answer.matchAll(/\]\((?:\.\.\/topics\/)?([a-z0-9-]+)\.md\)/g)].map(match => topicFromSlug(match[1], lookups)).filter((item): item is string => !!item))];
  const subject = title.replace(/^Roadmap: /, "").replace(/ study path$/, "");
  const names = roadmapNames(path, subject, isIndex, isRole);
  const topics = topic ? [topic] : ["roadmaps"];
  return {
    id: `${path}#roadmap`,
    kind: "roadmap",
    parentId: null,
    question: title,
    prompt: null,
    answer,
    // Role roadmaps open with the role's one-line description; study paths and index pages need no summary.
    summary: isRole ? summarize(answer) : "",
    codeBlocks: [],
    visuals: [],
    contentType: "roadmap",
    domain: "roadmap",
    topics,
    section: ["Roadmaps", isRole ? "Roles" : "Topics"],
    difficulty: null,
    keywords: [...new Set([...names.map(name => name.toLowerCase()), ...extractKeywords(title, "", topics)])].slice(0, 24),
    names,
    ...(linked.length ? { relatedTopics: linked.filter(item => item !== topic) } : {}),
    source: { path, startLine: titleAt + 1, endLine: lines.length - (lines.at(-1) === "" ? 1 : 0) },
    contentHash: hash(`${title}\n${answer}`),
  };
}

/** Role roadmaps answer to every name of their role ("SRE roadmap" → Site Reliability Engineer). */
export function linkRoadmapsToRoles(entries: QuestionEntry[]): void {
  const roles = new Map(entries.filter(entry => entry.kind === "role").map(role => [role.question.replace(/^What does an? /, "").replace(/ do\?$/, ""), role]));
  for (const entry of entries) {
    if (entry.kind !== "roadmap" || !entry.question.startsWith("Roadmap: ")) continue;
    const role = roles.get(entry.question.slice("Roadmap: ".length));
    if (role?.names) entry.names = [...new Set([...(entry.names ?? []), ...role.names])];
  }
}
