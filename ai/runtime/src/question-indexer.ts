// ---------- Small text helpers ----------

const EMOJI = /\p{Extended_Pictographic}|️|‍/gu;
const KEYCAP = /[0-9#*]️?⃣/gu;

/** Removes emoji, markdown emphasis, escapes and leading numbering from a heading. */
export function cleanHeading(raw: string): string {
  const cleaned = raw
    .replace(KEYCAP, "")
    .replace(EMOJI, "")
    .replace(/\\([_*`#\[\]()!-])/g, "$1")
    .replace(/\*\*|__/g, "")
    .replace(/^[\s↳—–:-]+/, "")
    .replace(/^follow-?up\s*:\s*/i, "")
    .replace(/^(q?\d+[.)]\s+)/i, "");
  return trimEndWhere(cleaned, char => /[\s_*]/.test(char)).trim();
}

export function slugify(text: string): string {
  const dashed = text
    .toLowerCase()
    .replace(/`/g, "")
    .replace(/[^a-z0-9]+/g, "-");
  const slug = trimChars(dashed, "-");
  if (!slug) return "entry";
  if (slug.length <= 64) return slug;
  const cut = slug.slice(0, 64);
  return cut.slice(0, cut.lastIndexOf("-") > 30 ? cut.lastIndexOf("-") : 64);
}

export function hash(text: string, length = 16): string {
  return createHash("sha256").update(text).digest("hex").slice(0, length);
}

/** Drops blank lines and `---` rules from both ends. */
export function trimBlock(lines: string[]): string[] {
  const isFiller = (line: string) => line.trim() === "" || /^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(line);
  let start = 0;
  let end = lines.length;
  while (start < end && isFiller(lines[start])) start++;
  while (end > start && isFiller(lines[end - 1])) end--;
  return lines.slice(start, end);
}

export function plainText(markdown: string): string {
  const withoutImages = markdown.replace(/!\[[^\]]*\]\([^)]*\)/g, "");
  return stripTags(unlinkMarkdown(withoutImages))
    .replace(KEYCAP, "")
    .replace(EMOJI, "")
    .replace(/\\([_*`#\[\]()!-])/g, "$1")
    .replace(/\*\*|__|`/g, "")
    .replace(/^\s*([-*+]|\d+\.)\s+/gm, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** First prose paragraph of an answer, ignoring code, headings, tables and images. */
export function summarize(answer: string, maxLength = 320): string {
  const withoutCode = answer.replace(/^\s*(```|~~~)[\s\S]*?^\s*\1\s*$/gm, "\n");
  const paragraphs = withoutCode.split(/\n\s*\n/);
  for (const paragraph of paragraphs) {
    const lines = paragraph
      .split("\n")
      .filter(line => !/^\s*(#{1,6}\s|\||!\[|<img|-{3,}\s*$)/.test(line));
    const text = plainText(lines.join("\n"));
    if (text.length < 15) continue;
    return truncate(text, maxLength);
  }
  // Table-only content (common in reference notes): "Cell 1: Cell 2; ..." from the body rows.
  const rows = withoutCode
    .split("\n")
    .filter(line => /^\s*\|/.test(line) && !/^\s*\|[\s:|-]+\|\s*$/.test(line))
    .slice(1)
    .map(line => line.split("|").slice(1, 3).map(cell => plainText(cell)).filter(Boolean).join(": "))
    .filter(Boolean);
  return rows.length ? truncate(rows.join("; "), maxLength) : "";
}

function truncate(text: string, maxLength: number): string {
  if (text.length <= maxLength) return text;
  const cut = text.slice(0, maxLength);
  return cut.slice(0, cut.lastIndexOf(" ") > 0 ? cut.lastIndexOf(" ") : maxLength) + "…";
}

export function extractCodeBlocks(markdown: string): CodeBlock[] {
  const blocks: CodeBlock[] = [];
  // Some questions quote their snippet ("> ```java"); read those like any other block.
  const unquoted = markdown.replace(/^[ \t]*> ?/gm, "");
  const fence = /^\s*(```|~~~)\s*([\w+#.-]*)[^\n]*\n([\s\S]*?)^\s*\1\s*$/gm;
  for (const match of unquoted.matchAll(fence)) {
    const code = match[3].trimEnd();
    if (code.trim()) blocks.push({ language: (match[2] || "text").toLowerCase(), code });
  }
  return blocks;
}

const STOPWORDS = new Set(
  ("a an and are as at be between by can could difference differences do does explain for from give how i if in into is it its " +
    "me my of on or our should so than that the their them then there these they this through to us use used using vs walk was " +
    "we what when where which while who why will with would you your about some any each other more most also different " +
    "work works mean means example real world simple terms someone new tell describe")
    .split(" "),
);

/** Bold labels authors use for layout, not meaning. */
const LABELS = new Set(["code example", "example", "answer", "note", "fix", "why", "output", "explanation", "summary", "key points", "pros", "cons"]);

export function extractKeywords(question: string, answer: string, topics: string[]): string[] {
  const words = new Set<string>();
  const add = (term: string) => {
    const lower = term.toLowerCase();
    let value = trimEndWhere(trimStartWhere(lower, char => !/[a-z0-9@#.]/.test(char)), char => !/[a-z0-9#+)]/.test(char));
    if (value.endsWith(")") && !value.includes("(")) value = value.slice(0, -1);
    if (value.includes("(") && !value.includes(")")) value += ")";
    if (value.length > 1 && !STOPWORDS.has(value) && !LABELS.has(value) && !/^\d+$/.test(value)) words.add(value);
  };
  for (const code of question.matchAll(/`([^`]+)`/g)) add(code[1].replace(/\(\)$/, ""));
  for (const token of question.replace(/`/g, " ").match(/[A-Za-z0-9@#][A-Za-z0-9.+#@-]*/g) ?? []) add(token);
  let bold = 0;
  for (const term of answer.matchAll(/\*\*([^*\n]{2,40})\*\*/g)) {
    if (bold++ >= 8) break;
    const text = plainText(term[1]);
    if (text && !/[:?]$/.test(text)) add(text);
  }
  for (const topic of topics) add(topic);
  return [...words].slice(0, 24);
}

/** A question's own level line, written right under the question: "**Level:** 🟢 Beginner". */
const LEVEL_LINE = /^\s*\*\*Level:\*\*\s*(?:🟢|🟡|🔴)?\s*(beginner|intermediate|advanced)\s*$/i;

/** Takes the level line out of a question's lines (the first non-empty line), returning its level. */
export function takeLevelLine(lines: string[]): { level: Difficulty | null; lines: string[] } {
  const first = lines.findIndex(line => line.trim() !== "");
  const match = first >= 0 ? LEVEL_LINE.exec(lines[first]) : null;
  if (!match) return { level: null, lines };
  return { level: match[1].toLowerCase() as Difficulty, lines: trimBlock([...lines.slice(0, first), ...lines.slice(first + 1)]) };
}

function difficultyFrom(section: string[]): Difficulty | null {
  const text = section.join(" ").toLowerCase();
  if (/\b(advanced|expert|senior)\b/.test(text)) return "advanced";
  if (/\bintermediate\b/.test(text)) return "intermediate";
  if (/\b(beginner|basics?)\b/.test(text)) return "beginner";
  return null;
}

// ---------- Repository lookups ----------

interface ContentIndexDocument {
  path: string;
  domain: string;
  content_type: string;
  canonical_concept: string | null;
  related_concepts: string[];
}

export function readText(relativePath: string): string {
  return readFileSync(resolve(REPOSITORY_ROOT, relativePath), "utf8").replace(/^﻿/, "").replace(/\r\n?/g, "\n");
}

function walk(relativeDir: string, filter: (path: string) => boolean): string[] {
  const absolute = resolve(REPOSITORY_ROOT, relativeDir);
  if (!existsSync(absolute)) return [];
  const results: string[] = [];
  for (const name of readdirSync(absolute)) {
    const child = posix.join(relativeDir, name);
    if (statSync(resolve(REPOSITORY_ROOT, child)).isDirectory()) results.push(...walk(child, filter));
    else if (filter(child)) results.push(child);
  }
  return results.sort(byText);
}

export interface Lookups {
  documents: Map<string, ContentIndexDocument>;
  concepts: string[];
  visualsByName: Map<string, string>;
  /** topic → alias words, from search-vocabulary.json; used to link Atlas roles to learning topics. */
  topicAliases: Record<string, string[]>;
  /** topicAliases plus roleSkillAliases: links job roles to learning topics. */
  roleAliases: Record<string, string[]>;
}

function loadLookups(): Lookups {
  const index = JSON.parse(readText(CONTENT_INDEX_PATH)) as { documents: ContentIndexDocument[] };
  const documents = new Map(index.documents.map(document => [document.path, document]));
  const concepts = [...new Set(index.documents.map(document => document.canonical_concept).filter((c): c is string => !!c))].sort(byText);
  const visualsByName = new Map<string, string>();
  for (const path of walk(VISUAL_ROOT, p => /\.(png|jpe?g|gif|svg|webp)$/i.test(p))) {
    const name = posix.basename(path).toLowerCase();
    if (!visualsByName.has(name)) visualsByName.set(name, path);
  }
  const vocabulary = existsSync(resolve(REPOSITORY_ROOT, VOCABULARY_PATH))
    ? (JSON.parse(readText(VOCABULARY_PATH)) as { topicAliases?: Record<string, string[]>; roleSkillAliases?: Record<string, string[]> })
    : {};
  const topicAliases = vocabulary.topicAliases ?? {};
  const roleAliases: Record<string, string[]> = {};
  for (const source of [topicAliases, vocabulary.roleSkillAliases ?? {}]) for (const [topic, words] of Object.entries(source)) roleAliases[topic] = [...(roleAliases[topic] ?? []), ...words];
  return { documents, concepts, visualsByName, topicAliases, roleAliases };
}

function resolveVisual(reference: string, sourcePath: string, lookups: Lookups): { path: string | null; exists: boolean } {
  const src = reference.split(/\s+/)[0].replace(/(?:^<)|(?:>$)/g, "");
  if (src.startsWith("data:")) return { path: null, exists: false };
  const candidate = src.startsWith(LEGACY_ASSET_PREFIX)
    ? posix.join(VISUAL_ROOT, src.slice(LEGACY_ASSET_PREFIX.length))
    : posix.normalize(posix.join(posix.dirname(sourcePath), decodeURI(src)));
  if (existsSync(resolve(REPOSITORY_ROOT, candidate))) return { path: candidate, exists: true };
  const byName = lookups.visualsByName.get(posix.basename(src).toLowerCase());
  return byName ? { path: byName, exists: true } : { path: candidate, exists: false };
}

function extractVisuals(lines: Line[], sourcePath: string, placement: VisualRef["placement"], lookups: Lookups): VisualRef[] {
  const visuals: VisualRef[] = [];
  // Image tags inside code samples are example code, not diagrams.
  const text = lines.filter(line => !line.inFence).map(line => line.text).join("\n");
  const found: Array<{ reference: string; alt: string }> = [];
  for (const match of text.matchAll(/!\[([^\]]*)\]\(([^)]+)\)/g)) found.push({ alt: match[1], reference: match[2].trim() });
  for (const match of text.matchAll(/<img\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/gi)) {
    found.push({ reference: match[1], alt: /\balt=["']([^"']*)["']/i.exec(match[0])?.[1] ?? "" });
  }
  for (const item of found) {
    const external = /^(https?:)?\/\//i.test(item.reference);
    const resolved = external ? { path: item.reference, exists: true } : resolveVisual(item.reference, sourcePath, lookups);
    visuals.push({ ...resolved, origin: external ? "external" : "repository", reference: item.reference, alt: withoutImageSuffix(item.alt), placement });
  }
  return visuals;
}

function topicsFor(document: ContentIndexDocument | undefined, section: string[], lookups: Lookups): string[] {
  const topics = new Set<string>();
  if (document?.canonical_concept) topics.add(document.canonical_concept);
  for (const concept of document?.related_concepts ?? []) topics.add(concept);
  // Sections that name a concept (e.g. "## Angular" inside a mixed file) add that concept.
  const heading = ` ${section.join(" ").toLowerCase().replace(/[^a-z0-9.]+/g, " ")} `;
  for (const concept of lookups.concepts) {
    const name = posix.basename(concept).replace(/-/g, " ");
    if (heading.includes(` ${name} `)) topics.add(concept);
  }
  return [...topics];
}

// ---------- Markdown parsing ----------

export interface Line {
  text: string;
  number: number;
  inFence: boolean;
  heading: { level: number; raw: string } | null;
  role: "question" | "follow-up" | "answer-marker" | null;
}

function classify(raw: string): Line["role"] {
  const text = raw.trim();
  if (/^#{1,6}\s/.test(text)) {
    const body = text.replace(/^#{1,6}\s+/, "");
    if (/^📝/.test(body) && /answer/i.test(body)) return "answer-marker";
    if (/^(\*\*)?↳/.test(body) || /^(\*\*)?follow-?up\b/i.test(body)) return "follow-up";
    if (/^❓/.test(body) || /^Q\d+\.\s+\S/.test(body)) return "question";
    return null;
  }
  if (/^❓\s*\S/.test(text)) return "question";
  if (/^\*\*answer:?\*\*:?$/i.test(text)) return "answer-marker";
  return null;
}

export function scanLines(content: string): Line[] {
  let fence: string | null = null;
  const lines: Line[] = content.split("\n").map((text, index) => {
    const fenceMatch = /^\s*(```|~~~)/.exec(text);
    if (fenceMatch) {
      const opening = fence === null;
      if (opening) fence = fenceMatch[1];
      else if (fenceMatch[1] === fence) fence = null;
      return { text, number: index + 1, inFence: true, heading: null, role: null };
    }
    if (fence !== null) return { text, number: index + 1, inFence: true, heading: null, role: null };
    const heading = parseHeading(text.trim());
    return {
      text,
      number: index + 1,
      inFence: false,
      heading,
      role: classify(text),
    };
  });
  // Files with "### ❓" headings use bare "❓ ..." lines as bullet points inside answers.
  const headingQuestions = lines.some(line => line.heading && line.role === "question");
  if (headingQuestions) for (const line of lines) if (!line.heading && line.role === "question") line.role = null;
  return lines;
}

/**
 * Heading levels used as section titles in this file: any level-1/2 heading that sits directly
 * above a question. Other level-1/2 headings are treated as part of an answer (e.g. "## User Model").
 */
function sectionLevels(lines: Line[]): Set<number> {
  const levels = new Set<number>();
  lines.forEach((line, index) => {
    if (line.role !== "question") return;
    for (let back = index - 1; back >= 0; back--) {
      const previous = lines[back];
      if (previous.role) return;
      if (previous.heading) {
        if (previous.heading.level <= 2) levels.add(previous.heading.level);
        return;
      }
    }
  });
  return levels;
}

interface Draft {
  kind: QuestionEntryKind;
  title: string;
  parentKey: number | null;
  startLine: number;
  section: string[];
  promptLines: Line[];
  answerLines: Line[];
  answerStarted: boolean;
  sectionVisualLines: Line[];
}

function sectionPath(crumbs: Map<number, string>): string[] {
  return [...crumbs.entries()].sort((a, b) => a[0] - b[0]).map(([, text]) => text).filter(Boolean);
}

function setCrumb(crumbs: Map<number, string>, level: number, text: string): void {
  for (const key of [...crumbs.keys()]) if (key >= level) crumbs.delete(key);
  crumbs.set(level, text);
}

/** Running state while splitting a file into questions and their follow-ups. */
interface QuestionParse {
  breaking: Set<number>;
  crumbs: Map<number, string>;
  drafts: Draft[];
  current: Draft | null;
  /** Index (in drafts) of the last main question; follow-ups attach to it. */
  lastMain: number | null;
  /** Lines before the first question of a section (e.g. a section diagram). */
  pendingVisualLines: Line[];
}

function closeDraft(state: QuestionParse): void {
  if (state.current) state.drafts.push(state.current);
  state.current = null;
}

function startQuestion(state: QuestionParse, line: Line): void {
  closeDraft(state);
  const isFollowUp = line.role === "follow-up" && state.lastMain !== null;
  const raw = line.heading ? line.heading.raw : line.text.trim();
  state.current = {
    kind: isFollowUp ? "follow-up" : "question",
    title: cleanHeading(raw),
    parentKey: isFollowUp ? state.lastMain : null,
    startLine: line.number,
    section: sectionPath(state.crumbs),
    promptLines: [],
    answerLines: [],
    answerStarted: false,
    sectionVisualLines: state.pendingVisualLines,
  };
  state.pendingVisualLines = [];
  if (!isFollowUp) state.lastMain = state.drafts.length;
}

/** A body line: before the answer marker it belongs to the prompt, after it to the answer. */
function addBodyLine(draft: Draft, line: Line): void {
  if (line.role === "answer-marker") {
    draft.answerStarted = true;
    return;
  }
  (draft.answerStarted ? draft.answerLines : draft.promptLines).push(line);
}

function parseQuestions(lines: Line[]): Draft[] {
  const state: QuestionParse = {
    breaking: sectionLevels(lines),
    crumbs: new Map(),
    drafts: [],
    current: null,
    lastMain: null,
    pendingVisualLines: [],
  };
  for (const line of lines) {
    if (line.role === "question" || line.role === "follow-up") {
      startQuestion(state, line);
    } else if (line.heading && !line.role && state.breaking.has(line.heading.level)) {
      closeDraft(state);
      setCrumb(state.crumbs, line.heading.level, cleanHeading(line.heading.raw));
    } else if (state.current) {
      addBodyLine(state.current, line);
    } else {
      state.pendingVisualLines.push(line);
    }
  }
  closeDraft(state);
  return state.drafts;
}

/** For files with no questions (reference notes): one entry per heading up to level 3. */
function parseNotes(lines: Line[]): Draft[] {
  const crumbs = new Map<number, string>();
  const drafts: Draft[] = [];
  let current: Draft | null = null;
  for (const line of lines) {
    if (line.heading && line.heading.level <= 3) {
      if (current) drafts.push(current);
      const title = cleanHeading(line.heading.raw);
      current = {
        kind: "note",
        title,
        parentKey: null,
        startLine: line.number,
        section: sectionPath(crumbs),
        promptLines: [],
        answerLines: [],
        answerStarted: true,
        sectionVisualLines: [],
      };
      setCrumb(crumbs, line.heading.level, title);
      continue;
    }
    current?.answerLines.push(line);
  }
  if (current) drafts.push(current);
  return drafts;
}

// ---------- Building entries ----------

/** The Atlas, generated roadmaps and ordinary notes each have their own builder. */
function entriesForFile(path: string, content: string, lookups: Lookups): QuestionEntry[] {
  if (path === ATLAS_PATH) return buildAtlasEntries(path, content, lookups);
  if (isGeneratedRoadmap(path, content)) return [buildRoadmapEntry(path, content, lookups)];
  return buildEntries(path, content, lookups);
}

function buildEntries(sourcePath: string, content: string, lookups: Lookups): QuestionEntry[] {
  const lines = scanLines(content);
  const hasQuestions = lines.some(line => line.role === "question");
  const drafts = hasQuestions ? parseQuestions(lines) : parseNotes(lines);
  const document = lookups.documents.get(sourcePath);
  const usedIds = new Set<string>();
  const idsByDraft: string[] = [];
  const entries: QuestionEntry[] = [];

  drafts.forEach(draft => {
    let promptLines = trimBlock(draft.promptLines.map(line => line.text));
    let answerLines = trimBlock(draft.answerLines.map(line => line.text));
    // A question with no "📝 Answer" marker: everything below the question is the answer.
    if (!draft.answerStarted) {
      answerLines = promptLines;
      promptLines = [];
    }
    // "**Level:** 🟢 Beginner" under the question sets its level; it isn't part of the answer text.
    let level: Difficulty | null = null;
    if (draft.kind === "question") {
      const fromPrompt = takeLevelLine(promptLines);
      if (fromPrompt.level) ({ level, lines: promptLines } = fromPrompt);
      else ({ level, lines: answerLines } = takeLevelLine(answerLines));
    }
    const answer = answerLines.join("\n");
    const prompt = promptLines.length ? promptLines.join("\n") : null;
    const visuals = [
      ...extractVisuals(draft.sectionVisualLines, sourcePath, "section", lookups),
      ...extractVisuals([...draft.promptLines, ...draft.answerLines], sourcePath, "answer", lookups),
    ];
    if (draft.kind === "note" && !answer.trim() && visuals.length === 0) {
      idsByDraft.push("");
      return;
    }

    let id = `${sourcePath}#${slugify(draft.title)}`;
    let suffix = 2;
    while (usedIds.has(id)) {
      id = `${sourcePath}#${slugify(draft.title)}-${suffix}`;
      suffix++;
    }
    usedIds.add(id);
    idsByDraft.push(id);

    const allLines = [...draft.promptLines, ...draft.answerLines].filter(line => line.text.trim() && !/^\s*-{3,}\s*$/.test(line.text));
    const endLine = allLines.length ? allLines[allLines.length - 1].number : draft.startLine;
    const topics = topicsFor(document, [...draft.section, ...(draft.kind === "note" ? [draft.title] : [])], lookups);
    const codeSource = [prompt ?? "", answer].join("\n");

    entries.push({
      id,
      kind: draft.kind,
      parentId: draft.parentKey !== null ? idsByDraft[draft.parentKey] || null : null,
      question: draft.title,
      prompt,
      answer,
      summary: summarize(answer),
      codeBlocks: extractCodeBlocks(codeSource),
      visuals,
      contentType: document?.content_type ?? sourcePath.split("/")[0],
      domain: document?.domain ?? sourcePath.split("/")[1] ?? "",
      topics,
      section: draft.section,
      difficulty: level ?? difficultyFrom(draft.section),
      keywords: extractKeywords(draft.title, answer, topics),
      source: { path: sourcePath, startLine: draft.startLine, endLine },
      contentHash: hash(`${draft.title}\n${prompt ?? ""}\n${answer}`),
    });
  });
  return entries;
}

export function listSourceFiles(): string[] {
  // *.backup.md files are migration leftovers, not content.
  const files = SOURCE_ROOTS.flatMap(root => walk(root, path => path.endsWith(".md") && !posix.basename(path).startsWith("_") && !path.endsWith(".backup.md")));
  return existsSync(resolve(REPOSITORY_ROOT, ATLAS_PATH)) ? [...files, ATLAS_PATH] : files;
}

export function buildQuestionIndex(generatedAt = new Date().toISOString()): QuestionIndex {
  const lookups = loadLookups();
  const files: QuestionIndexFileStats[] = [];
  const entries: QuestionEntry[] = [];
  const fingerprint = createHash("sha256");

  for (const path of listSourceFiles()) {
    const content = readText(path);
    fingerprint.update(`${path}\n${hash(content, 64)}\n`);
    const fileEntries = entriesForFile(path, content, lookups);
    entries.push(...fileEntries);
    files.push({
      path,
      questions: fileEntries.filter(entry => entry.kind === "question").length,
      followUps: fileEntries.filter(entry => entry.kind === "follow-up").length,
      notes: fileEntries.filter(entry => entry.kind === "note").length,
      roles: fileEntries.filter(entry => entry.kind === "role").length,
      terms: fileEntries.filter(entry => entry.kind === "term").length,
      roadmaps: fileEntries.filter(entry => entry.kind === "roadmap").length,
      withoutAnswer: fileEntries.filter(entry => !entry.answer.trim()).length,
      missingVisuals: fileEntries.flatMap(entry => entry.visuals).filter(visual => !visual.exists).length,
    });
  }
  // Parser changes must also change the fingerprint, so include this file's own source.
  fingerprint.update(readFileSync(fileURLToPath(import.meta.url)));
  fingerprint.update(readFileSync(fileURLToPath(new URL("./atlas-indexer.js", import.meta.url))));
  fingerprint.update(readFileSync(fileURLToPath(new URL("./roadmap-indexer.js", import.meta.url))));
  linkRoadmapsToRoles(entries);
  fingerprint.update(JSON.stringify(lookups.roleAliases));

  const visuals = entries.flatMap(entry => entry.visuals);
  return {
    schema_version: QUESTION_INDEX_SCHEMA_VERSION,
    repository: "Tech-Mastery-Hub",
    generated_at: generatedAt,
    source_fingerprint: fingerprint.digest("hex"),
    stats: {
      files: files.length,
      entries: entries.length,
      questions: entries.filter(entry => entry.kind === "question").length,
      followUps: entries.filter(entry => entry.kind === "follow-up").length,
      notes: entries.filter(entry => entry.kind === "note").length,
      roles: entries.filter(entry => entry.kind === "role").length,
      terms: entries.filter(entry => entry.kind === "term").length,
      roadmaps: entries.filter(entry => entry.kind === "roadmap").length,
      codeBlocks: entries.reduce((total, entry) => total + entry.codeBlocks.length, 0),
      visuals: visuals.length,
      missingVisuals: visuals.filter(visual => !visual.exists).length,
    },
    files,
    entries,
  };
}

function renderReport(index: QuestionIndex): string {
  const rows = index.files.map(
    file => `| \`${file.path}\` | ${file.questions} | ${file.followUps} | ${file.notes} | ${file.roles} | ${file.terms} | ${file.withoutAnswer} | ${file.missingVisuals} |`,
  );
  const empty = index.entries.filter(entry => !entry.answer.trim());
  const missing = index.entries.flatMap(entry => entry.visuals.filter(visual => !visual.exists).map(visual => ({ entry, visual })));
  const untagged = new Map<string, number>();
  for (const entry of index.entries) if (!entry.topics.length) untagged.set(entry.source.path, (untagged.get(entry.source.path) ?? 0) + 1);
  const byTopic = new Map<string, number>();
  for (const entry of index.entries) for (const topic of entry.topics.length ? entry.topics : ["(none)"]) byTopic.set(topic, (byTopic.get(topic) ?? 0) + 1);
  return [
    "# Question Index Report",
    "",
    `Generated by \`ai/runtime/src/question-indexer.ts\`. Fingerprint \`${index.source_fingerprint.slice(0, 12)}\`.`,
    "",
    "## Totals",
    "",
    "| Files | Entries | Questions | Follow-ups | Notes | Roles | Terms | Code blocks | Visuals | Missing visuals |",
    "|---|---|---|---|---|---|---|---|---|---|",
    `| ${index.stats.files} | ${index.stats.entries} | ${index.stats.questions} | ${index.stats.followUps} | ${index.stats.notes} | ${index.stats.roles} | ${index.stats.terms} | ${index.stats.codeBlocks} | ${index.stats.visuals} | ${index.stats.missingVisuals} |`,
    "",
    "## Entries per topic",
    "",
    "| Topic | Entries |",
    "|---|---|",
    ...[...byTopic.entries()].sort((a, b) => b[1] - a[1]).map(([topic, count]) => `| ${topic} | ${count} |`),
    "",
    "## Per file",
    "",
    "| File | Questions | Follow-ups | Notes | Roles | Terms | No answer | Missing visuals |",
    "|---|---|---|---|---|---|---|---|",
    ...rows,
    "",
    "## Entries with no topic",
    "",
    "The content index gives these files no concept, so they are left untagged rather than guessed.",
    "",
    ...(untagged.size ? [...untagged.entries()].map(([path, count]) => `- \`${path}\` (${count})`) : ["None."]),
    "",
    "## Entries without an answer",
    "",
    ...(empty.length ? empty.map(entry => `- \`${entry.source.path}:${entry.source.startLine}\` — ${entry.question}`) : ["None."]),
    "",
    "## Image references that do not resolve",
    "",
    ...(missing.length
      ? missing.map(({ entry, visual }) => `- \`${entry.source.path}:${entry.source.startLine}\` — \`${visual.reference}\``)
      : ["None."]),
    "",
  ].join("\n");
}

function withoutTimestamp(index: QuestionIndex): string {
  return JSON.stringify({ ...index, generated_at: "" });
}

function main(): void {
  const target = resolve(REPOSITORY_ROOT, QUESTION_INDEX_PATH);
  const existing = existsSync(target) ? (JSON.parse(readFileSync(target, "utf8")) as QuestionIndex) : null;
  const fresh = buildQuestionIndex();

  if (process.argv.includes("--check")) {
    if (!existing || withoutTimestamp(existing) !== withoutTimestamp({ ...fresh })) {
      process.stderr.write(`Question index is out of date. Run: npm run question-index\n`);
      process.exit(1);
    }
    process.stdout.write(`Question index is up to date (${fresh.stats.entries} entries).\n`);
    return;
  }

  // Keep the old timestamp when nothing changed, so re-running gives no diff.
  const unchanged = existing && withoutTimestamp(existing) === withoutTimestamp(fresh);
  const output = unchanged && existing ? { ...fresh, generated_at: existing.generated_at } : fresh;
  writeFileSync(target, JSON.stringify(output, null, 2) + "\n", "utf8");
  writeFileSync(resolve(REPOSITORY_ROOT, REPORT_PATH), renderReport(output), "utf8");
  const s = output.stats;
  process.stdout.write(
    `${unchanged ? "Unchanged" : "Wrote"} ${QUESTION_INDEX_PATH}: ${s.entries} entries from ${s.files} files ` +
      `(${s.questions} questions, ${s.followUps} follow-ups, ${s.notes} notes, ${s.roles} roles, ${s.terms} terms, ${s.roadmaps} roadmaps, ${s.codeBlocks} code blocks, ` +
      `${s.visuals} visuals, ${s.missingVisuals} missing).\n`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
