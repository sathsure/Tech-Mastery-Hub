/**
 * Builds draft roadmaps from the notes:
 *   roadmap/topics/<topic>.md   study path per topic: the interview sections in the author's order, as a checklist
 *   roadmap/topics/README.md    "start here": suggested learning tracks
 *   roadmap/roles/<role>.md     roadmap per IT role: the topics its skills map to, ordered by prerequisites
 *   roadmap/roles/README.md     index of role roadmaps
 *   scripts/reports/content-gaps.md   what the roles need that the notes don't cover yet
 *
 * Every checklist item links to the note it comes from. The topic order and tracks are a suggestion
 * (marked as such in each file). Files start with GENERATED_MARKER; delete that line to take a file
 * over by hand, and the generator will leave it alone.
 *
 * Usage (after `npm run build`):  node dist/roadmap-generator.js [--check]
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { QuestionEntry } from "./question-index-contracts.js";
import { buildQuestionIndex, REPOSITORY_ROOT } from "./question-indexer.js";
import { entityKey, loadVocabulary } from "./question-search.js";
import { TOPIC_LABELS } from "./topic-labels.js";

export const GENERATED_MARKER = "<!-- generated by ai/runtime/src/roadmap-generator.ts — delete this line to edit this file by hand -->";
const DRAFT_NOTE = "> **Draft, generated from your notes.** Every item links to the note it comes from. The order of topics is a suggestion; review and adjust it.";

/**
 * Suggested prerequisites between learning topics. This is the generator's teaching order,
 * not repository content, and every file says so.
 */
export const PREREQUISITES: Record<string, string[]> = {
  html: [],
  css: ["html"],
  javascript: ["html"],
  typescript: ["javascript"],
  "web-vitals": ["html", "css", "javascript"],
  react: ["javascript"],
  angular: ["typescript"],
  rxjs: ["typescript"],
  nodejs: ["javascript"],
  "rest-api": [],
  "web-architecture": ["nodejs", "rest-api"],
  java: [],
  spring: ["java"],
  "spring-security": ["spring"],
  "database/sql": [],
  microservices: ["rest-api"],
  "spring-cloud": ["spring", "microservices"],
  devops: [],
  aws: ["devops"],
};

export const TRACKS: Array<{ name: string; description: string; topics: string[] }> = [
  { name: "Frontend", description: "Build user interfaces for the browser.", topics: ["html", "css", "javascript", "typescript", "web-vitals", "react", "angular", "rxjs"] },
  { name: "Backend with Java", description: "Build services with Java and Spring.", topics: ["java", "database/sql", "rest-api", "spring", "spring-security", "microservices", "spring-cloud"] },
  { name: "Backend with Node.js", description: "Build services with JavaScript on the server.", topics: ["javascript", "nodejs", "rest-api", "database/sql", "web-architecture"] },
  { name: "DevOps and cloud", description: "Ship, run and scale applications.", topics: ["devops", "aws", "microservices"] },
];

const STAGE_NAMES = ["Foundations", "Core skills", "Frameworks and depth", "Specialisation", "Architecture"];

const label = (topic: string) => TOPIC_LABELS[topic] ?? topic;
const topicSlug = (topic: string) => topic.replace(/[^a-z0-9]+/gi, "-").toLowerCase();
const roleSlug = (name: string) => name.toLowerCase().replace(/\(.*?\)/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
/** "What does a DevOps Engineer do?" → "DevOps Engineer" */
export const roleName = (role: QuestionEntry) => role.question.replace(/^What does an? /, "").replace(/ do\?$/, "");
const link = (fromDir: string, path: string) => posix.relative(fromDir, path);
const plural = (count: number, word: string) => `${count} ${word}${count === 1 ? "" : "s"}`;

function topicLevels(topics: string[]): Map<string, number> {
  const levels = new Map<string, number>();
  const visit = (topic: string): number => {
    if (levels.has(topic)) return levels.get(topic)!;
    const prerequisites = (PREREQUISITES[topic] ?? []).filter(item => topics.includes(item));
    const level = prerequisites.length ? Math.max(...prerequisites.map(visit)) + 1 : 0;
    levels.set(topic, level);
    return level;
  };
  topics.forEach(visit);
  return levels;
}

/** All prerequisites of the given topics that the notes cover, so a roadmap never skips a step. */
function withPrerequisites(topics: string[], covered: Set<string>): string[] {
  const result = new Set<string>();
  const add = (topic: string) => {
    if (result.has(topic) || !covered.has(topic)) return;
    result.add(topic);
    (PREREQUISITES[topic] ?? []).forEach(add);
  };
  topics.forEach(add);
  return [...result];
}

interface Material {
  questions: QuestionEntry[];
  practice: QuestionEntry[];
  followUps: Map<string, QuestionEntry[]>;
}

function materialFor(entries: QuestionEntry[], topic: string): Material {
  const learning = entries.filter(entry => entry.topics.includes(topic) && (entry.contentType === "interview" || entry.contentType === "practice"));
  const followUps = new Map<string, QuestionEntry[]>();
  for (const entry of learning) if (entry.kind === "follow-up" && entry.parentId) followUps.set(entry.parentId, [...(followUps.get(entry.parentId) ?? []), entry]);
  const main = learning.filter(entry => entry.kind !== "follow-up");
  return {
    questions: main.filter(entry => entry.source.path.startsWith("interview/")),
    practice: main.filter(entry => entry.source.path.startsWith("practice/")),
    followUps,
  };
}

function item(entry: QuestionEntry, fromDir: string, indent = ""): string {
  return `${indent}- [ ] [${entry.question.replace(/[[\]]/g, "")}](${link(fromDir, entry.source.path)}) · line ${entry.source.startLine}`;
}

// ---------- Topic study paths ----------

function topicPath(topic: string, entries: QuestionEntry[], plans: RolePlan[]): string {
  const dir = "roadmap/topics";
  const material = materialFor(entries, topic);
  const groups = new Map<string, QuestionEntry[]>();
  for (const entry of material.questions) {
    const key = `${entry.source.path}|${entry.section.join(" › ")}`;
    groups.set(key, [...(groups.get(key) ?? []), entry]);
  }
  const files = new Set(material.questions.map(entry => entry.source.path));
  const stages = [...groups.entries()].map(([key, list], index) => {
    const [path, section] = key.split("|");
    const title = section || (files.size > 1 ? posix.basename(path, ".md") : "Questions");
    const lines = list.flatMap(entry => [item(entry, dir), ...(material.followUps.get(entry.id) ?? []).map(child => item(child, dir, "  "))]);
    return [`### ${index + 1}. ${title}`, "", ...lines, ""].join("\n");
  });
  const concept = `knowledge/concepts/${topic}/README.md`;
  const visuals = [...new Map(entries.filter(entry => entry.topics.includes(topic)).flatMap(entry => entry.visuals).filter(visual => visual.origin === "repository" && visual.path).map(visual => [visual.path!, visual])).values()];
  // Only roles that have a roadmap, so every link resolves.
  const usedBy = plans.filter(plan => plan.core.includes(topic)).map(plan => plan.name).sort();
  const prerequisites = PREREQUISITES[topic] ?? [];
  const total = material.questions.length + [...material.followUps.values()].reduce((sum, list) => sum + list.length, 0);

  return [
    GENERATED_MARKER,
    `# ${label(topic)} study path`,
    "",
    `A checklist of the ${plural(total, "interview question")} and ${plural(material.practice.length, "practice problem")} on ${label(topic)} in your notes, in the order they were written.`,
    "",
    DRAFT_NOTE,
    "",
    "## Before you start",
    "",
    existsSync(resolve(REPOSITORY_ROOT, concept)) ? `- Read the concept overview: [${label(topic)} concepts](${link(dir, concept)})` : null,
    prerequisites.length ? `- Suggested first: ${prerequisites.map(item => `[${label(item)}](../topics/${topicSlug(item)}.md)`).join(", ")}` : "- No prerequisites: a good place to start.",
    "",
    "## Interview questions",
    "",
    ...stages,
    material.practice.length ? ["## Practice", "", ...material.practice.map(entry => item(entry, dir)), ""].join("\n") : null,
    visuals.length ? ["## Diagrams in your notes", "", ...visuals.map(visual => `- [${visual.alt || posix.basename(visual.path!)}](${link(dir, visual.path!)})`), ""].join("\n") : null,
    usedBy.length ? ["## Roles that use this", "", usedBy.map(name => `[${name}](../roles/${roleSlug(name)}.md)`).join(" · "), ""].join("\n") : null,
  ].filter((part): part is string => part !== null).join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
}

function topicsReadme(topics: string[], counts: Map<string, number>): string {
  const tracks = TRACKS.map(track => {
    const steps = track.topics.filter(topic => topics.includes(topic));
    return [`### ${track.name}`, "", track.description, "", ...steps.map((topic, index) => `${index + 1}. [ ] [${label(topic)}](../topics/${topicSlug(topic)}.md) — ${plural(counts.get(topic) ?? 0, "question")}`), ""].join("\n");
  });
  return [
    GENERATED_MARKER,
    "# Where to start: learning tracks",
    "",
    "Pick a track and work through the study paths in order. Each study path is a checklist of the questions in your notes.",
    "",
    DRAFT_NOTE,
    "",
    ...tracks,
    "## All study paths",
    "",
    ...topics.map(topic => `- [${label(topic)}](../topics/${topicSlug(topic)}.md) — ${plural(counts.get(topic) ?? 0, "question")}`),
    "",
    "Looking for a job role instead? See the [role roadmaps](../roles/README.md).",
    "",
  ].join("\n");
}

// ---------- Role roadmaps ----------

function roleField(role: QuestionEntry, field: string): string | null {
  const line = role.answer.split("\n").find(text => text.startsWith(`- **${field}:**`));
  return line ? line.replace(`- **${field}:**`, "").trim() : null;
}

/** Topics whose aliases appear in the given text. */
function topicsIn(text: string, aliases: Record<string, string[]>, covered: Set<string>): string[] {
  const padded = ` ${entityKey(text)} `;
  return Object.entries(aliases).filter(([topic, words]) => covered.has(topic) && words.some(word => padded.includes(` ${entityKey(word)} `))).map(([topic]) => topic).sort();
}

/** Comma-separated skills that match no topic in the notes. */
function uncovered(text: string | null, aliases: Record<string, string[]>): string[] {
  if (!text) return [];
  return text.split(/,\s*/).map(part => part.trim()).filter(part => part && !Object.values(aliases).flat().some(word => ` ${entityKey(part)} `.includes(` ${entityKey(word)} `)));
}

interface RolePlan {
  role: QuestionEntry;
  name: string;
  slug: string;
  core: string[];
  extra: string[];
  missing: string[];
}

function planRole(role: QuestionEntry, aliases: Record<string, string[]>, covered: Set<string>): RolePlan | null {
  const name = roleName(role);
  const coreText = ["Languages", "Frameworks / Standards", "Technical skills"].map(field => roleField(role, field) ?? "").join(", ");
  const direct = topicsIn(coreText, aliases, covered);
  const viaTools = topicsIn(roleField(role, "Tools") ?? "", aliases, covered).filter(topic => !direct.includes(topic));
  if (!direct.length && !viaTools.length) return null;
  const core = withPrerequisites(direct.length ? direct : viaTools, covered);
  const missing = ["Languages", "Frameworks / Standards", "Tools"].flatMap(field => uncovered(roleField(role, field), aliases));
  return { role, name, slug: roleSlug(name), core, extra: viaTools.filter(topic => !core.includes(topic)), missing: [...new Set(missing)] };
}

function roleRoadmap(plan: RolePlan, entries: QuestionEntry[], counts: Map<string, number>): string {
  const dir = "roadmap/roles";
  const { role, name, core } = plan;
  const levels = topicLevels(core);
  const stages = new Map<number, string[]>();
  for (const topic of core) stages.set(levels.get(topic)!, [...(stages.get(levels.get(topic)!) ?? []), topic]);
  const stageBlocks = [...stages.entries()].sort((a, b) => a[0] - b[0]).map(([level, topics], index) => {
    const lines = topics.sort((a, b) => (counts.get(b) ?? 0) - (counts.get(a) ?? 0)).flatMap(topic => {
      const starters = materialFor(entries, topic).questions.slice(0, 3);
      return [
        `- [ ] **${label(topic)}** — ${plural(counts.get(topic) ?? 0, "question")} in your notes · [study path](../topics/${topicSlug(topic)}.md)`,
        ...starters.map(entry => `  - [${entry.question.replace(/[[\]]/g, "")}](${link(dir, entry.source.path)}) · line ${entry.source.startLine}`),
      ];
    });
    return [`## Stage ${index + 1} — ${STAGE_NAMES[Math.min(level, STAGE_NAMES.length - 1)]}`, "", ...lines, ""].join("\n");
  });
  const practiceCount = core.reduce((sum, topic) => sum + materialFor(entries, topic).practice.length, 0);
  const field = (title: string) => roleField(role, title);
  const atlasLink = `[IT Roles & Terminology Atlas](${link(dir, role.source.path)}), line ${role.source.startLine}`;

  return [
    GENERATED_MARKER,
    `# Roadmap: ${name}`,
    "",
    `A step-by-step plan to become a ${name}, built from ${plural(core.length, "topic")} in your notes. ${role.summary}`,
    "",
    DRAFT_NOTE,
    "",
    "## The role",
    "",
    `- **What they do:** ${role.summary}`,
    field("Typical experience to be hired") ? `- **Typical experience to be hired:** ${field("Typical experience to be hired")}` : null,
    field("Technical skills") ? `- **Technical skills:** ${field("Technical skills")}` : null,
    `- **Source:** ${atlasLink}`,
    "",
    ...stageBlocks,
    `## Stage ${stages.size + 1} — Interview preparation`,
    "",
    "- [ ] Finish the study paths above",
    practiceCount ? `- [ ] Solve the ${plural(practiceCount, "practice problem")} in these topics` : null,
    ...core.slice(0, 4).map(topic => `- [ ] Mock interview in the tutor: \`/interview ${label(topic)}\``),
    `- [ ] Ask the tutor: \`${name} salary\` and \`What does a ${name} do?\``,
    "",
    plan.extra.length ? ["## Also useful", "", `The role's tools touch ${plan.extra.map(topic => `[${label(topic)}](../topics/${topicSlug(topic)}.md)`).join(", ")}.`, ""].join("\n") : null,
    plan.missing.length ? ["## Not in your notes yet", "", "The role lists these, but your notes don't cover them. Learn them from other sources, or add notes for them:", "", plan.missing.map(skill => `\`${skill}\``).join(" · "), ""].join("\n") : null,
    field("Next moves — grow") ? ["## Where it leads", "", `- **Grow:** ${field("Next moves — grow")}`, ""].join("\n") : null,
  ].filter((part): part is string => part !== null).join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
}

function rolesReadme(plans: RolePlan[], skipped: QuestionEntry[]): string {
  const families = new Map<string, RolePlan[]>();
  for (const plan of plans) families.set(plan.role.section[1] ?? "Other", [...(families.get(plan.role.section[1] ?? "Other") ?? []), plan]);
  return [
    GENERATED_MARKER,
    "# Role roadmaps",
    "",
    `Step-by-step roadmaps for ${plural(plans.length, "IT role")}, built from the skills each role lists in the IT Roles & Terminology Atlas and the topics in your notes.`,
    "",
    DRAFT_NOTE,
    "",
    ...[...families.entries()].flatMap(([family, list]) => [`## ${family}`, "", ...list.map(plan => `- [${plan.name}](../roles/${plan.slug}.md) — ${plan.core.map(label).join(", ")}`), ""]),
    "## No roadmap yet",
    "",
    "These roles don't use any topic in your notes yet (their skills are outside the current notes):",
    "",
    skipped.map(role => roleName(role)).sort().join(" · "),
    "",
    "New to tech? Start with the [learning tracks](../topics/README.md).",
    "",
  ].join("\n");
}

// ---------- Gap report ----------

function gapReport(plans: RolePlan[], skipped: QuestionEntry[], topics: string[], counts: Map<string, number>): string {
  const demand = new Map<string, Set<string>>();
  for (const plan of plans) for (const skill of plan.missing) demand.set(skill, new Set([...(demand.get(skill) ?? []), plan.name]));
  const top = [...demand.entries()].sort((a, b) => b[1].size - a[1].size || a[0].localeCompare(b[0])).slice(0, 25);
  const thin = topics.filter(topic => (counts.get(topic) ?? 0) < 15).sort((a, b) => (counts.get(a) ?? 0) - (counts.get(b) ?? 0));
  return [
    "# Content gaps",
    "",
    "Generated by `ai/runtime/src/roadmap-generator.ts`. Where to add notes next, based on what the IT roles in the Atlas need and what the notes cover.",
    "",
    "## Skills most roles need that the notes don't cover",
    "",
    "| Skill | Roles that list it |",
    "|---|---|",
    ...top.map(([skill, roles]) => `| ${skill} | ${roles.size} |`),
    "",
    "## Topics with few questions",
    "",
    ...(thin.length ? thin.map(topic => `- ${label(topic)}: ${plural(counts.get(topic) ?? 0, "question")}`) : ["None."]),
    "",
    "## Roles with no matching topic",
    "",
    `${plural(skipped.length, "role")} have no roadmap because none of their skills appear in the notes:`,
    "",
    skipped.map(role => roleName(role)).sort().join(" · "),
    "",
  ].join("\n");
}

// ---------- Run ----------

export function generateRoadmaps(): Map<string, string> {
  const index = buildQuestionIndex("roadmaps");
  const entries = index.entries.filter(entry => !entry.source.path.startsWith("roadmap/"));
  const aliases = loadVocabulary().topicAliases;
  const counts = new Map<string, number>();
  for (const entry of entries) {
    if (entry.contentType !== "interview" && entry.contentType !== "practice") continue;
    for (const topic of entry.topics) counts.set(topic, (counts.get(topic) ?? 0) + 1);
  }
  const topics = Object.keys(PREREQUISITES).filter(topic => counts.has(topic));
  const covered = new Set(topics);
  const roles = entries.filter(entry => entry.kind === "role");
  const plans = roles.map(role => planRole(role, aliases, covered)).filter((plan): plan is RolePlan => plan !== null).sort((a, b) => a.name.localeCompare(b.name));
  const skipped = roles.filter(role => !plans.some(plan => plan.role === role));

  const files = new Map<string, string>();
  files.set("roadmap/topics/README.md", topicsReadme(topics, counts));
  for (const topic of topics) files.set(`roadmap/topics/${topicSlug(topic)}.md`, topicPath(topic, entries, plans));
  files.set("roadmap/roles/README.md", rolesReadme(plans, skipped));
  for (const plan of plans) files.set(`roadmap/roles/${plan.slug}.md`, roleRoadmap(plan, entries, counts));
  files.set("scripts/reports/content-gaps.md", gapReport(plans, skipped, topics, counts));
  return files;
}

/** Files without the marker belong to a person and are never overwritten. */
function ownedByGenerator(path: string): boolean {
  const target = resolve(REPOSITORY_ROOT, path);
  if (!existsSync(target)) return true;
  return path.startsWith("scripts/reports/") || readFileSync(target, "utf8").includes(GENERATED_MARKER);
}

function main(): void {
  const files = generateRoadmaps();
  const check = process.argv.includes("--check");
  const stale: string[] = [];
  const kept: string[] = [];
  let written = 0;
  for (const [path, content] of files) {
    if (!ownedByGenerator(path)) {
      kept.push(path);
      continue;
    }
    const target = resolve(REPOSITORY_ROOT, path);
    // Ignore line endings: Git may check files out with CRLF on Windows.
    const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
    if (current === content) continue;
    if (check) {
      stale.push(path);
      continue;
    }
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content, "utf8");
    written++;
  }
  if (check) {
    if (stale.length) {
      process.stderr.write(`Roadmaps are out of date (${stale.length} files). Run: npm run roadmaps\n`);
      process.exit(1);
    }
    process.stdout.write(`Roadmaps are up to date (${files.size} files).\n`);
    return;
  }
  process.stdout.write(`Roadmaps: ${files.size} files, ${written} written${kept.length ? `, ${kept.length} kept (edited by hand): ${kept.join(", ")}` : ""}.\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
