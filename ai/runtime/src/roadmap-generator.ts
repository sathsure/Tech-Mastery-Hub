const STAGE_NAMES = ["Foundations", "Core skills", "Frameworks and depth", "Specialisation", "Architecture"];

const label = (topic: string) => TOPIC_LABELS[topic] ?? topic;
export const topicSlug = (topic: string) => topic.replace(/[^a-z0-9]+/gi, "-").toLowerCase();
const roleSlug = (name: string) => replaceParenGroups(name.toLowerCase(), "").replace(/[^a-z0-9]+/g, "-").replace(/(?:^-)|(?:-$)/g, "");
/** "What does a DevOps Engineer do?" → "DevOps Engineer" */
export const roleName = (role: QuestionEntry) => role.question.replace(/^What does an? /, "").replace(/ do\?$/, "");
const link = (fromDir: string, path: string) => posix.relative(fromDir, path);
const plural = (count: number, word: string) => `${count} ${word}${count === 1 ? "" : "s"}`;

export function topicLevels(topics: string[]): Map<string, number> {
  const levels = new Map<string, number>();
  const visit = (topic: string): number => {
    if (levels.has(topic)) return levels.get(topic)!;
    const prerequisites = (PREREQUISITES[topic] ?? []).filter(item => topics.includes(item));
    const level = prerequisites.length ? Math.max(...prerequisites.map(visit)) + 1 : 0;
    levels.set(topic, level);
    return level;
  };
  topics.forEach(visit);
  return levels;
}

/** All prerequisites of the given topics that the notes cover, so a roadmap never skips a step. */
export function withPrerequisites(topics: string[], covered: Set<string>): string[] {
  const result = new Set<string>();
  const add = (topic: string) => {
    if (result.has(topic) || !covered.has(topic)) return;
    result.add(topic);
    (PREREQUISITES[topic] ?? []).forEach(add);
  };
  topics.forEach(add);
  return [...result];
}

interface Material {
  questions: QuestionEntry[];
  practice: QuestionEntry[];
  followUps: Map<string, QuestionEntry[]>;
}

function materialFor(entries: QuestionEntry[], topic: string): Material {
  const learning = entries.filter(entry => entry.topics.includes(topic) && (entry.contentType === "interview" || entry.contentType === "practice"));
  const followUps = new Map<string, QuestionEntry[]>();
  for (const entry of learning) if (entry.kind === "follow-up" && entry.parentId) followUps.set(entry.parentId, [...(followUps.get(entry.parentId) ?? []), entry]);
  const main = learning.filter(entry => entry.kind !== "follow-up");
  return {
    questions: main.filter(entry => entry.source.path.startsWith("interview/")),
    practice: main.filter(entry => entry.source.path.startsWith("practice/")),
    followUps,
  };
}

/** A study path is read in order: numbered steps, with follow-up questions nested under their question. */
function entryLink(entry: QuestionEntry, fromDir: string): string {
  return `[${entry.question.replace(/[[\]]/g, "")}](${link(fromDir, entry.source.path)})`;
}

function item(entry: QuestionEntry, fromDir: string, position: number): string {
  return `${position}. ${entryLink(entry, fromDir)}`;
}

function childItem(entry: QuestionEntry, fromDir: string): string {
  return `   - ${entryLink(entry, fromDir)}`;
}

const studyPath = (topic: string) => `[${label(topic)}](../topics/${topicSlug(topic)}.md)`;

// ---------- Topic study paths ----------

function topicPath(topic: string, entries: QuestionEntry[], plans: RolePlan[]): string {
  const dir = "roadmap/topics";
  const material = materialFor(entries, topic);
  const groups = new Map<string, QuestionEntry[]>();
  for (const entry of material.questions) {
    const key = `${entry.source.path}|${entry.section.join(" › ")}`;
    groups.set(key, [...(groups.get(key) ?? []), entry]);
  }
  const files = new Set(material.questions.map(entry => entry.source.path));
  const stages = [...groups.entries()].map(([key, list], index) => {
    const [path, section] = key.split("|");
    const title = section || (files.size > 1 ? posix.basename(path, ".md") : "Questions");
    const lines = list.flatMap((entry, position) => [item(entry, dir, position + 1), ...(material.followUps.get(entry.id) ?? []).map(child => childItem(child, dir))]);
    return [`## ${index + 1}. ${title}`, "", ...lines, ""].join("\n");
  });
  const concept = `knowledge/concepts/${topic}/README.md`;
  const visuals = [...new Map(entries.filter(entry => entry.topics.includes(topic)).flatMap(entry => entry.visuals).filter(visual => visual.origin === "repository" && visual.path).map(visual => [visual.path!, visual])).values()];
  // Only roles that have a roadmap, so every link resolves.
  const usedBy = plans.filter(plan => plan.core.includes(topic)).map(plan => plan.name).sort(byText);
  const prerequisites = PREREQUISITES[topic] ?? [];

  return [
    GENERATED_MARKER,
    `# ${label(topic)} study path`,
    "",
    "## Prerequisites",
    "",
    ...(prerequisites.length ? prerequisites.map(item => `- ${studyPath(item)}`) : ["- None. This is a starting point."]),
    existsSync(resolve(REPOSITORY_ROOT, concept)) ? `- Overview: [${label(topic)} concepts](${link(dir, concept)})` : null,
    "",
    ...stages,
    material.practice.length ? ["## Practice", "", ...material.practice.map((entry, position) => item(entry, dir, position + 1)), ""].join("\n") : null,
    visuals.length ? ["## Diagrams", "", ...visuals.map(visual => `- [${visual.alt || posix.basename(visual.path!)}](${link(dir, visual.path!)})`), ""].join("\n") : null,
    usedBy.length ? ["## Related roles", "", usedBy.map(name => `[${name}](../roles/${roleSlug(name)}.md)`).join(" · "), ""].join("\n") : null,
  ].filter((part): part is string => part !== null).join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
}

function topicsReadme(topics: string[]): string {
  const tracks = TRACKS.map(track => {
    const steps = track.topics.filter(topic => topics.includes(topic));
    return [`## ${track.name}`, "", track.description, "", ...steps.map((topic, index) => `${index + 1}. [ ] ${studyPath(topic)}`), ""].join("\n");
  });
  return [
    GENERATED_MARKER,
    "# Where to start",
    "",
    "Pick a track and follow the study paths in order.",
    "",
    ...tracks,
    "Looking for a job role? See the [role roadmaps](../roles/README.md).",
    "",
  ].join("\n");
}

// ---------- Role roadmaps ----------

function roleField(role: QuestionEntry, field: string): string | null {
  const line = role.answer.split("\n").find(text => text.startsWith(`- **${field}:**`));
  return line ? line.replace(`- **${field}:**`, "").trim() : null;
}

/** Topics whose aliases appear in the given text. */
function topicsIn(text: string, aliases: Record<string, string[]>, covered: Set<string>): string[] {
  const padded = ` ${entityKey(text)} `;
  return Object.entries(aliases).filter(([topic, words]) => covered.has(topic) && words.some(word => padded.includes(` ${entityKey(word)} `))).map(([topic]) => topic).sort(byText);
}

/** Comma-separated skills that match no topic in the notes. */
/** "A, B (C, D), E" → ["A", "B (C, D)", "E"]: commas inside parentheses don't split. */
function splitSkills(text: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let current = "";
  for (const char of text) {
    if (char === "(") depth++;
    if (char === ")") depth = Math.max(0, depth - 1);
    if (char === "," && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else {
      current += char;
    }
  }
  parts.push(current.trim());
  return parts.filter(Boolean);
}

function uncovered(text: string | null, aliases: Record<string, string[]>): string[] {
  if (!text) return [];
  const words = Object.values(aliases).flat();
  // "—" means the role has none; it is not a skill.
  return splitSkills(text).filter(part => part !== "—" && !words.some(word => ` ${entityKey(part)} `.includes(` ${entityKey(word)} `)));
}

interface RolePlan {
  role: QuestionEntry;
  name: string;
  slug: string;
  core: string[];
  extra: string[];
  missing: string[];
}

/** Topics every developer needs; on their own they say nothing about a particular role. */
const GENERIC_TOPICS = new Set(["git", "behavioral"]);

function planRole(role: QuestionEntry, aliases: Record<string, string[]>, covered: Set<string>): RolePlan | null {
  const name = roleName(role);
  const coreText = ["Languages", "Frameworks / Standards", "Technical skills"].map(field => roleField(role, field) ?? "").join(", ");
  const direct = topicsIn(coreText, aliases, covered);
  const viaTools = topicsIn(roleField(role, "Tools") ?? "", aliases, covered).filter(topic => !direct.includes(topic));
  if (!direct.length && !viaTools.length) return null;
  const core = withPrerequisites(direct.length ? direct : viaTools, covered);
  // Git or interview skills alone don't make a learning path for a role.
  if (core.every(topic => GENERIC_TOPICS.has(topic))) return null;
  const missing = ["Languages", "Frameworks / Standards", "Tools"].flatMap(field => uncovered(roleField(role, field), aliases));
  return { role, name, slug: roleSlug(name), core, extra: viaTools.filter(topic => !core.includes(topic)), missing: [...new Set(missing)] };
}

function roleRoadmap(plan: RolePlan): string {
  const { role, name, core } = plan;
  const levels = topicLevels(core);
  const byLevel = new Map<number, string[]>();
  for (const topic of core) byLevel.set(levels.get(topic)!, [...(byLevel.get(levels.get(topic)!) ?? []), topic].sort(byText));
  const ordered = [...byLevel.entries()].sort((a, b) => a[0] - b[0]);
  // With several levels, the first level is what to know before starting; otherwise nothing is required.
  const prerequisites = ordered.length > 1 ? ordered[0][1] : [];
  const stages = ordered.length > 1 ? ordered.slice(1) : ordered;
  const stageBlocks = stages.map(([level, topics], index) =>
    [`### Stage ${index + 1}: ${STAGE_NAMES[Math.min(Math.max(level, 1), STAGE_NAMES.length - 1)]}`, "", ...topics.map(topic => `- [ ] ${studyPath(topic)}`), ""].join("\n"),
  );
  const field = (title: string) => roleField(role, title);
  const experience = field("Typical experience to be hired");

  // Six sections only: overview, prerequisites, stages, also useful, also needed, where it leads.
  return [
    GENERATED_MARKER,
    `# Roadmap: ${name}`,
    "",
    "## Role overview",
    "",
    role.summary,
    "",
    "## Prerequisites",
    "",
    ...(prerequisites.length ? prerequisites.map(topic => `- ${studyPath(topic)}`) : ["- None. Start with Stage 1."]),
    experience && !/^0\+/.test(experience) ? `- Usually ${experience.replace(/yrs?$/, "years")} of experience when hired` : null,
    "",
    "## Learning stages",
    "",
    ...stageBlocks,
    plan.extra.length ? ["## Also useful", "", plan.extra.map(studyPath).join(", "), ""].join("\n") : null,
    plan.missing.length ? ["## Also needed", "", plan.missing.join(", "), ""].join("\n") : null,
    field("Next moves — grow") ? ["## Where it leads", "", `Grow: ${field("Next moves — grow")!.replace(/\*\*(lead|pivot):\*\*/g, (_, word: string) => `${word[0].toUpperCase()}${word.slice(1)}:`)}`, ""].join("\n") : null,
  ].filter((part): part is string => part !== null).join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
}

function rolesReadme(plans: RolePlan[]): string {
  const families = new Map<string, RolePlan[]>();
  for (const plan of plans) families.set(plan.role.section[1] ?? "Other", [...(families.get(plan.role.section[1] ?? "Other") ?? []), plan]);
  return [
    GENERATED_MARKER,
    "# Role roadmaps",
    "",
    ...[...families.entries()].flatMap(([family, list]) => [`## ${family}`, "", ...list.map(plan => `- [${plan.name}](../roles/${plan.slug}.md)`), ""]),
    "New to tech? Start with the [learning tracks](../topics/README.md).",
    "",
  ].join("\n");
}

// ---------- Gap report ----------

function gapReport(plans: RolePlan[], skipped: QuestionEntry[], topics: string[], counts: Map<string, number>): string {
  const demand = new Map<string, Set<string>>();
  for (const plan of plans) for (const skill of plan.missing) demand.set(skill, new Set([...(demand.get(skill) ?? []), plan.name]));
  const top = [...demand.entries()].sort((a, b) => b[1].size - a[1].size || a[0].localeCompare(b[0])).slice(0, 25);
  const thin = topics.filter(topic => (counts.get(topic) ?? 0) < 15).sort((a, b) => (counts.get(a) ?? 0) - (counts.get(b) ?? 0));
  return [
    "# Content gaps",
    "",
    "Generated by `ai/runtime/src/roadmap-generator.ts`. Where to add notes next, based on what the IT roles in the Atlas need and what the notes cover.",
    "",
    "## Skills most roles need that the notes don't cover",
    "",
    "| Skill | Roles that list it |",
    "|---|---|",
    ...top.map(([skill, roles]) => `| ${skill} | ${roles.size} |`),
    "",
    "## Topics with few questions",
    "",
    ...(thin.length ? thin.map(topic => `- ${label(topic)}: ${plural(counts.get(topic) ?? 0, "question")}`) : ["None."]),
    "",
    "## Roles with no matching topic",
    "",
    `${plural(skipped.length, "role")} have no roadmap because none of their skills appear in the notes:`,
    "",
    skipped.map(role => roleName(role)).sort(byText).join(" · "),
    "",
  ].join("\n");
}

// ---------- Run ----------

export function generateRoadmaps(): Map<string, string> {
  const index = buildQuestionIndex("roadmaps");
  const entries = index.entries.filter(entry => !entry.source.path.startsWith("roadmap/"));
  const aliases = loadVocabulary().topicAliases;
  const counts = new Map<string, number>();
  for (const entry of entries) {
    if (entry.contentType !== "interview" && entry.contentType !== "practice") continue;
    for (const topic of entry.topics) counts.set(topic, (counts.get(topic) ?? 0) + 1);
  }
  const topics = Object.keys(PREREQUISITES).filter(topic => counts.has(topic));
  const covered = new Set(topics);
  const roles = entries.filter(entry => entry.kind === "role");
  const plans = roles.map(role => planRole(role, aliases, covered)).filter((plan): plan is RolePlan => plan !== null).sort((a, b) => a.name.localeCompare(b.name));
  const skipped = roles.filter(role => !plans.some(plan => plan.role === role));

  const files = new Map<string, string>();
  files.set("roadmap/topics/README.md", topicsReadme(topics));
  for (const topic of topics) files.set(`roadmap/topics/${topicSlug(topic)}.md`, topicPath(topic, entries, plans));
  files.set("roadmap/roles/README.md", rolesReadme(plans));
  for (const plan of plans) files.set(`roadmap/roles/${plan.slug}.md`, roleRoadmap(plan));
  files.set("scripts/reports/content-gaps.md", gapReport(plans, skipped, topics, counts));
  return files;
}

/** Files without the marker belong to a person and are never overwritten. */
function ownedByGenerator(path: string): boolean {
  const target = resolve(REPOSITORY_ROOT, path);
  if (!existsSync(target)) return true;
  return path.startsWith("scripts/reports/") || readFileSync(target, "utf8").includes(GENERATED_MARKER);
}

function main(): void {
  const files = generateRoadmaps();
  const check = process.argv.includes("--check");
  const stale: string[] = [];
  const kept: string[] = [];
  let written = 0;
  for (const [path, content] of files) {
    if (!ownedByGenerator(path)) {
      kept.push(path);
      continue;
    }
    const target = resolve(REPOSITORY_ROOT, path);
    // Ignore line endings: Git may check files out with CRLF on Windows.
    const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
    if (current === content) continue;
    if (check) {
      stale.push(path);
      continue;
    }
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content, "utf8");
    written++;
  }
  if (check) {
    if (stale.length) {
      process.stderr.write(`Roadmaps are out of date (${stale.length} files). Run: npm run roadmaps\n`);
      process.exit(1);
    }
    process.stdout.write(`Roadmaps are up to date (${files.size} files).\n`);
    return;
  }
  process.stdout.write(`Roadmaps: ${files.size} files, ${written} written${kept.length ? `, ${kept.length} kept (edited by hand): ${kept.join(", ")}` : ""}.\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
