/**
 * Builds draft roadmaps from the notes:
 *   roadmap/topics/<topic>.md   study path per topic: the interview sections in the author's order, as a checklist
 *   roadmap/topics/README.md    "start here": suggested learning tracks
 *   roadmap/roles/<role>.md     roadmap per IT role: the topics its skills map to, ordered by prerequisites
 *   roadmap/roles/README.md     index of role roadmaps
 *   scripts/reports/content-gaps.md   what the roles need that the notes don't cover yet
 *
 * Every checklist item links to the note it comes from. The topic order and tracks are a suggestion
 * (marked as such in each file). Files start with GENERATED_MARKER; delete that line to take a file
 * over by hand, and the generator will leave it alone.
 *
 * Usage (after `npm run build`):  node dist/roadmap-generator.js [--check]
 */
